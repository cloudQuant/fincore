def render_factor_html(document: ReportDocument, *, language: str = _DEFAULT_LANGUAGE) -> str:
    """Render a self-contained bilingual HTML report from a report document."""

    if not isinstance(document, ReportDocument):
        raise TypeError("document must be a ReportDocument")
    return _render(document, language)


def write_factor_html(document: ReportDocument, target: str | Path, *, language: str = _DEFAULT_LANGUAGE) -> Path:
    """Write the rendered factor report and return its path."""

    path = Path(target)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_factor_html(document, language=language), encoding="utf-8")
    return path


def write_factor_report_from_model(
    model: FactorAnalysisModel,
    target: str | Path,
    *,
    title: str | None = None,
    language: str = _DEFAULT_LANGUAGE,
    loss_report: Any = None,
) -> Path:
    """Render one model; ``loss_report`` is optional preparation metadata."""

    _validate_language(language)
    if not isinstance(model, FactorAnalysisModel):
        raise TypeError("model must be a FactorAnalysisModel")
    document = build_factor_report(model, title=title or _default_title(language))
    document = _with_loss_metadata(document, loss_report)
    return write_factor_html(document, target, language=language)


def write_factor_report(
    factor: pd.Series,
    prices: pd.DataFrame,
    target: str | Path,
    *,
    periods: tuple[int, ...] = (1, 5, 20),
    quantiles: int = 5,
    max_loss: float = 1.0,
    title: str | None = None,
    language: str = _DEFAULT_LANGUAGE,
    next_open: bool = True,
) -> Path:
    """Prepare, analyze, and render one factor in a single call.

    ``prices`` must be a wide DataFrame indexed by date with one column per
    asset. ``factor`` must use a two-level ``(date, asset)`` MultiIndex.
    """

    _validate_language(language)
    if not isinstance(factor, pd.Series):
        raise TypeError("factor must be a pandas Series")
    if not isinstance(prices, pd.DataFrame):
        raise TypeError("prices must be a pandas DataFrame")
    if next_open:
        prices = prices.shift(-1)

    from fincore.factor_analysis.analysis import analyze_factor
    from fincore.factor_analysis.data import prepare_factor_data

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", pd.errors.PerformanceWarning)
        warnings.filterwarnings(
            "ignore",
            message="'freq' not set, using business day calendar",
            category=UserWarning,
        )
        prepared = prepare_factor_data(
            factor,
            prices,
            periods=tuple(periods),
            quantiles=quantiles,
            max_loss=max_loss,
        )
        model = analyze_factor(prepared.data, periods=None, turnover_periods=tuple(periods))
    return write_factor_report_from_model(
        model,
        target,
        title=title,
        language=language,
        loss_report=prepared.loss_report,
    )
