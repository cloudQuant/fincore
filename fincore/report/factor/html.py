def _validate_language(language: str) -> None:
    if language not in _LANGUAGES:
        raise ValueError(f"language must be one of {_LANGUAGES!r}")


def _default_title(language: str) -> str:
    return "因子分析报告" if language == "zh" else "Factor Analysis Report"


def _number(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _timestamp_points(values: pd.Series) -> list[list[Any]]:
    points = []
    for index, value in values.items():
        points.append([pd.Timestamp(cast("Any", index)).isoformat(), _number(value)])
    return points


def _histogram(series: Mapping[str, list[list[Any]]]) -> dict[str, Any]:
    values = [value for points in series.values() for _, value in points if value is not None]
    if not values:
        return {"categories": [], "series": {}}
    edges = np.histogram_bin_edges(np.asarray(values, dtype=float), bins=20)
    centers = ((edges[:-1] + edges[1:]) / 2.0).tolist()
    counts = {}
    for period, points in series.items():
        sample = [value for _, value in points if value is not None]
        counts[period] = [int(count) for count in np.histogram(sample, bins=edges)[0]]
    return {
        "categories": [f"{center:.3f}" for center in centers],
        "series": counts,
    }


def _chart_data(document: ReportDocument) -> dict[str, Any]:
    summary = document.section("factor_summary")
    information = document.section("factor_information")
    returns = document.section("factor_returns")
    turnover = document.section("factor_turnover")

    ic = {name.split(".", 1)[-1]: _timestamp_points(values) for name, values in information.series.items()}
    cumulative = {name.rsplit(".", 1)[-1]: _timestamp_points(values) for name, values in summary.series.items()}
    mean_returns = returns.tables["mean_returns_by_quantile"]
    quantile = {
        "categories": [str(value) for value in mean_returns.index],
        "series": {
            str(period): [_number(value * 10_000.0) for value in mean_returns[period]]
            for period in mean_returns.columns
        },
    }
    turnover_table = turnover.tables["mean_turnover_by_quantile"]
    turnover_data = {
        "categories": [str(value) for value in turnover_table.index],
        "series": {str(lag): [_number(value) for value in turnover_table[lag]] for lag in turnover_table.columns},
    }
    return {
        "ic": ic,
        "cumulative": cumulative,
        "quantile": quantile,
        "turnover": turnover_data,
        "distribution": _histogram(ic),
    }


def _json_for_script(value: Any) -> str:
    encoded = json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    return encoded.replace("</", "<\\/")


@lru_cache(maxsize=1)
def _echarts_script() -> str:
    path = Path(__file__).resolve().parents[1] / "assets" / "echarts.min.js"
    source = path.read_text(encoding="utf-8")
    return re.sub(r"</script", r"<\\/script", source, flags=re.IGNORECASE)


def _escaped(value: Any, *, quote: bool = False) -> str:
    return html.escape(str(value), quote=quote)


def _i18n(key: str, *, section: str | None = "sections") -> str:
    if section is None:
        zh = _TEXT["zh"][key]
        en = _TEXT["en"][key]
    else:
        zh = _TEXT["zh"][section][key]
        en = _TEXT["en"][section][key]
    return f'data-zh="{_escaped(zh, quote=True)}" data-en="{_escaped(en, quote=True)}"'


def _localized_table(
    frame: pd.DataFrame,
    language: str,
    *,
    index_name: str,
    index_labels: Mapping[str, Mapping[str, str]] | None = None,
    column_labels: Mapping[str, Mapping[str, str]] | None = None,
) -> str:
    data = frame.copy(deep=True)
    if index_labels:
        data.index = [index_labels.get(str(value), {}).get(language, str(value)) for value in data.index]
    data = data.reset_index()
    labels = column_labels or {}
    headers = [
        index_name,
        *[labels.get(str(column), {}).get(language, str(column)) for column in frame.columns],
    ]
    data.columns = headers
    return data.to_html(
        index=False,
        border=0,
        classes="data-table",
        na_rep="—",
        float_format=lambda value: f"{value:.6g}",
        escape=True,
    )


def _table_card(title_key: str, zh_table: str, en_table: str) -> str:
    zh_title = _TEXT["zh"]["tables"][title_key]
    en_title = _TEXT["en"]["tables"][title_key]
    return (
        '<div class="card table-card">'
        f'<h3 data-zh="{_escaped(zh_title, quote=True)}" data-en="{_escaped(en_title, quote=True)}">'
        f"{_escaped(zh_title)}</h3>"
        f'<div class="lang-block lang-zh">{zh_table}</div>'
        f'<div class="lang-block lang-en">{en_table}</div>'
        "</div>"
    )


def _table_pair(
    frame: pd.DataFrame,
    *,
    index_name_key: str,
    index_labels: Mapping[str, Mapping[str, str]] | None = None,
    column_labels: Mapping[str, Mapping[str, str]] | None = None,
) -> tuple[str, str]:
    tables = [
        _localized_table(
            frame,
            language,
            index_name=_TEXT[language]["tables"][index_name_key],
            index_labels=index_labels,
            column_labels=column_labels,
        )
        for language in _LANGUAGES
    ]
    return tables[0], tables[1]


def _column_labels() -> Mapping[str, Mapping[str, str]]:
    return {key: {"zh": value, "en": key} for key, value in _TEXT["zh"]["tables"]["columns"].items()}


def _row_labels() -> Mapping[str, Mapping[str, str]]:
    return {key: {"zh": value, "en": key} for key, value in _TEXT["zh"]["tables"]["row_labels"].items()}


def _coverage_frame(document: ReportDocument) -> pd.DataFrame:
    metadata = document.metadata
    summary = document.section("factor_summary").metrics
    forward_count = sum(int(value) for key, value in summary.items() if key.startswith("forward_return_count."))
    total_loss = metadata.get("total_loss")
    rows = {
        "input_cells": metadata.get("input_count", summary.get("observation_count", "—")),
        "finite_factor_cells": metadata.get("finite_factor_count", summary.get("finite_factor_count", "—")),
        "forward_return_cells": metadata.get("forward_returns_count", forward_count or "—"),
        "binning_cells": metadata.get("binning_count", "—"),
        "total_loss": f"{float(total_loss) * 100.0:.2f}%" if total_loss is not None else "—",
    }
    return pd.DataFrame({"value": list(rows.values())}, index=list(rows))


def _details_html(document: ReportDocument) -> str:
    information = document.section("factor_information").tables["information_summary"]
    quantile = document.section("factor_summary").tables["quantile_statistics"]
    returns = document.section("factor_returns").tables["returns_summary"]
    mean_returns = document.section("factor_returns").tables["mean_returns_by_quantile"]
    turnover = document.section("factor_turnover").tables["mean_turnover_by_quantile"]
    autocorr = document.section("factor_turnover").tables["rank_autocorrelation_summary"]

    ic_pair = _table_pair(information, index_name_key="period", column_labels=_column_labels())
    quantile_pair = _table_pair(quantile, index_name_key="quantile", column_labels=_column_labels())
    returns_pair = _table_pair(returns, index_name_key="metric", index_labels=_row_labels())
    mean_pair = _table_pair(mean_returns, index_name_key="quantile")
    turnover_pair = _table_pair(turnover, index_name_key="quantile")
    autocorr_pair = _table_pair(autocorr, index_name_key="metric", index_labels=_row_labels())
    cards = [
        _table_card("ic_summary", *ic_pair),
        _table_card("quantile_stats", *quantile_pair),
        _table_card("returns_summary", *returns_pair),
        _table_card("mean_returns", *mean_pair),
        _table_card("turnover", *turnover_pair),
        _table_card("autocorr", *autocorr_pair),
    ]
    return "".join(cards)


def _coverage_html(document: ReportDocument) -> str:
    return _coverage_card(_coverage_frame(document))


def _coverage_card(frame: pd.DataFrame) -> str:
    zh_labels = _TEXT["zh"]["tables"]["coverage_rows"]
    en_labels = _TEXT["en"]["tables"]["coverage_rows"]
    zh = _localized_table(
        frame,
        "zh",
        index_name=_TEXT["zh"]["tables"]["metric"],
        index_labels={key: {"zh": value, "en": en_labels.get(key, key)} for key, value in zh_labels.items()},
        column_labels={"value": {"zh": _TEXT["zh"]["tables"]["value"], "en": _TEXT["en"]["tables"]["value"]}},
    )
    en = _localized_table(
        frame,
        "en",
        index_name=_TEXT["en"]["tables"]["metric"],
        index_labels={key: {"zh": value, "en": en_labels.get(key, key)} for key, value in zh_labels.items()},
        column_labels={"value": {"zh": _TEXT["zh"]["tables"]["value"], "en": _TEXT["en"]["tables"]["value"]}},
    )
    return _table_card("coverage", zh, en)


def _format_number(value: Any, digits: int) -> str:
    number = _number(value)
    return "—" if number is None else f"{number:.{digits}f}"


def _format_count(value: Any) -> str:
    number = _number(value)
    return "—" if number is None else f"{round(number):,}"


def _kpi_cards(document: ReportDocument) -> str:
    summary = document.section("factor_summary")
    information = document.section("factor_information")
    periods = [name.split(".", 1)[-1] for name in information.series]
    cards = []
    for period in periods:
        ic_mean = summary.metrics.get(f"mean_information_coefficient.{period}")
        ic_ir = _table_value(information.tables["information_summary"], period, "Risk-Adjusted IC")
        ic_t = _table_value(information.tables["information_summary"], period, "t-stat(IC)")
        cards.append(
            _kpi_card(
                _TEXT["zh"]["cards"]["ic_mean"].format(period=period),
                _TEXT["en"]["cards"]["ic_mean"].format(period=period),
                _format_number(ic_mean, 4),
                _tone(ic_mean),
            )
        )
        cards.append(
            _kpi_card(
                _TEXT["zh"]["cards"]["ic_ir"].format(period=period),
                _TEXT["en"]["cards"]["ic_ir"].format(period=period),
                _format_number(ic_ir, 2),
                _tone(ic_ir),
            )
        )
        cards.append(
            _kpi_card(
                _TEXT["zh"]["cards"]["ic_t"].format(period=period),
                _TEXT["en"]["cards"]["ic_t"].format(period=period),
                _format_number(ic_t, 2),
                _tone(ic_t),
            )
        )
    coverage = _coverage_ratio(document)
    cards.append(
        _kpi_card(
            _TEXT["zh"]["cards"]["coverage"],
            _TEXT["en"]["cards"]["coverage"],
            "—" if coverage is None else f"{coverage * 100.0:.1f}%",
        )
    )
    cards.append(
        _kpi_card(
            _TEXT["zh"]["cards"]["observations"],
            _TEXT["en"]["cards"]["observations"],
            _format_count(summary.metrics.get("observation_count")),
        )
    )
    cards.append(
        _kpi_card(
            _TEXT["zh"]["cards"]["quantiles"],
            _TEXT["en"]["cards"]["quantiles"],
            _format_count(summary.metrics.get("quantile_count")),
        )
    )
    turnover_table = document.section("factor_turnover").tables["mean_turnover_by_quantile"]
    turnover_value = _number(turnover_table["1D"].mean()) if "1D" in turnover_table else None
    cards.append(
        _kpi_card(
            _TEXT["zh"]["cards"]["turnover"],
            _TEXT["en"]["cards"]["turnover"],
            _format_number(turnover_value, 3),
        )
    )
    return "".join(cards)


def _table_value(table: pd.DataFrame, index: Any, column: str) -> Any:
    try:
        return table.loc[index, column]
    except (KeyError, IndexError, TypeError):
        return None


def _tone(value: Any) -> str:
    number = _number(value)
    if number is None or number == 0:
        return ""
    return "positive" if number > 0 else "negative"


def _kpi_card(zh_label: str, en_label: str, value: str, tone: str = "") -> str:
    return (
        f'<div class="kpi {tone}">'
        f'<div class="kpi-label" data-zh="{_escaped(zh_label, quote=True)}" '
        f'data-en="{_escaped(en_label, quote=True)}">{_escaped(zh_label)}</div>'
        f'<div class="kpi-value">{_escaped(value)}</div>'
        "</div>"
    )


def _coverage_ratio(document: ReportDocument) -> float | None:
    metadata = document.metadata
    summary = document.section("factor_summary").metrics
    input_count = _number(metadata.get("input_count", summary.get("observation_count")))
    finite = _number(metadata.get("finite_factor_count", summary.get("finite_factor_count")))
    if input_count and finite is not None:
        return finite / input_count
    return _number(summary.get("coverage_ratio"))


def _with_loss_metadata(document: ReportDocument, loss_report: Any) -> ReportDocument:
    if loss_report is None:
        return document
    metadata = dict(document.metadata)
    metadata.update(
        {
            "input_count": int(loss_report.input_count),
            "finite_factor_count": int(loss_report.finite_factor_count),
            "forward_returns_count": int(loss_report.forward_returns_count),
            "binning_count": int(loss_report.binning_count),
            "total_loss": float(loss_report.total_loss),
        }
    )
    return replace(document, metadata=metadata)


